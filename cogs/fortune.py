class Fortune(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        self.logger = logging.getLogger(self.__class__.__name__)

    @commands.command(aliases=["luck"])
    async def fortune(self, ctx):
        """
        Reveal a random fortune
        This command can only be used by server boosters
        """

        if not ctx.author.premium_since:
            await ctx.reply("Only server boosters can use this command.")
            return

        fortune_text = random.choice(FORTUNES)

        self.logger.debug(f"Fortune given to {ctx.author}: {fortune_text}")

        await ctx.reply(fortune_text)


async def setup(bot):
    await bot.add_cog(Fortune(bot))
